// Phone language -> key in `names`: "pt_BR" and "zh_TW" first, then "pt"/"zh",
// then English. Norwegian may be reported as "no" or "nb".
var _langCache = null
function _lang() {
    if (_langCache !== null) return _langCache
    var full = Qt.locale().name              // e.g. "de_DE", "pt_BR", "zh_HK"
    var short = full.substring(0, 2)
    if (short === "no") short = "nb"
    if (names[full]) _langCache = full
    else if (names[short]) _langCache = short
    else _langCache = "en"
    return _langCache
}

// "ambientSoundMode" -> "Ambient sound mode"
function prettify(id) {
    if (!id) return ""
    var s = String(id).replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase()
    return s.charAt(0).toUpperCase() + s.slice(1)
}

function name(id) {
    var l = _lang()
    if (names[l][id]) return names[l][id]
    if (names.en[id]) return names.en[id]
    return prettify(id)
}

